package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	telegramAlias     = "telegram.prabu"
	secretConfigPath  = "channels.telegram.prabu.bot_token"
	channelEnablePath = "channels.telegram.prabu.enabled"
	agentWorkspace    = ".zeroclaw/agents/prabu/workspace"
	managedMarker     = "# Managed by prabu. Do not edit this file directly."
)

type setupConfig struct {
	provider    string
	model       string
	botToken    string
	providerKey string
}

type configPatchOperation struct {
	Operation string          `json:"op"`
	Path      string          `json:"path"`
	Value     json.RawMessage `json:"value"`
}

func configSeed(config setupConfig) ([]byte, error) {
	model, err := json.Marshal(config.model)
	if err != nil {
		return nil, fmt.Errorf("quote model name: %w", err)
	}
	content := fmt.Sprintf(`schema_version = 4

[providers.models.%s.prabu]
model = %s

[risk_profiles.prabu]
level = "supervised"
workspace_only = true
allowed_commands = ["omo"]
auto_approve = ["shell"]
always_ask = []

[agents.prabu]
model_provider = "%s.prabu"
risk_profile = "prabu"
channels = ["telegram.prabu"]

[channels.telegram.prabu]
enabled = false
mention_only = true
per_user_session = true

[tools]
optional = []

[shell_tool]
timeout_secs = 1800
`, config.provider, model, config.provider)
	return []byte(content), nil
}

func configPatch(config setupConfig) ([]byte, error) {
	operations := make([]configPatchOperation, 0, 16)
	if err := appendConfigPatch(&operations, "providers.models."+config.provider+".prabu.model", config.model); err != nil {
		return nil, err
	}
	if config.providerKey != "" {
		if err := appendConfigPatch(&operations, "providers.models."+config.provider+".prabu.api_key", config.providerKey); err != nil {
			return nil, err
		}
	}
	values := []configPatchOperation{
		{Operation: "add", Path: "/risk_profiles/prabu/level", Value: json.RawMessage(`"supervised"`)},
		{Operation: "add", Path: "/risk_profiles/prabu/workspace_only", Value: json.RawMessage("true")},
		{Operation: "add", Path: "/risk_profiles/prabu/allowed_commands", Value: json.RawMessage(`["omo"]`)},
		{Operation: "add", Path: "/risk_profiles/prabu/auto_approve", Value: json.RawMessage(`["shell"]`)},
		{Operation: "add", Path: "/risk_profiles/prabu/always_ask", Value: json.RawMessage("[]")},
		{Operation: "add", Path: "/channels/telegram/prabu/mention_only", Value: json.RawMessage("true")},
		{Operation: "add", Path: "/channels/telegram/prabu/per_user_session", Value: json.RawMessage("true")},
		{Operation: "add", Path: "/tools/optional", Value: json.RawMessage("[]")},
		{Operation: "add", Path: "/shell_tool/timeout_secs", Value: json.RawMessage("1800")},
	}
	operations = append(operations, values...)
	agentValues := []struct {
		path  string
		value string
	}{
		{path: "agents.prabu.model_provider", value: config.provider + ".prabu"},
		{path: "agents.prabu.risk_profile", value: "prabu"},
	}
	for _, entry := range agentValues {
		if err := appendConfigPatch(&operations, entry.path, entry.value); err != nil {
			return nil, err
		}
	}
	if err := appendConfigPatch(&operations, "agents.prabu.channels", []string{telegramAlias}); err != nil {
		return nil, err
	}
	if config.botToken != "" {
		if err := appendConfigPatch(&operations, secretConfigPath, config.botToken); err != nil {
			return nil, err
		}
		if err := appendConfigPatch(&operations, channelEnablePath, true); err != nil {
			return nil, err
		}
	}
	return json.Marshal(operations)
}

func appendConfigPatch[T any](operations *[]configPatchOperation, path string, value T) error {
	encoded, err := json.Marshal(value)
	if err != nil {
		return fmt.Errorf("encode ZeroClaw config patch value: %w", err)
	}
	*operations = append(*operations, configPatchOperation{
		Operation: "add",
		Path:      "/" + strings.ReplaceAll(path, ".", "/"),
		Value:     encoded,
	})
	return nil
}

func writeConfigSeed(path string, config setupConfig) error {
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("inspect ZeroClaw config %s: %w", path, err)
	}
	content, err := configSeed(config)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return fmt.Errorf("create ZeroClaw config directory: %w", err)
	}
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if errors.Is(err, os.ErrExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("create ZeroClaw config %s: %w", path, err)
	}
	writeErr := func() (writeErr error) {
		defer func() {
			writeErr = errors.Join(writeErr, file.Close())
		}()
		if _, err := file.Write(content); err != nil {
			return fmt.Errorf("write ZeroClaw config %s: %w", path, err)
		}
		if err := file.Sync(); err != nil {
			return fmt.Errorf("sync ZeroClaw config %s: %w", path, err)
		}
		return nil
	}()
	if writeErr != nil {
		removeErr := os.Remove(path)
		if removeErr != nil {
			return errors.Join(writeErr, fmt.Errorf("remove partial ZeroClaw config: %w", removeErr))
		}
		return writeErr
	}
	return nil
}

func writeAgentInstructions(home string) error {
	path := filepath.Join(home, agentWorkspace, "SOUL.md")
	start := "<!-- prabu:omo-delegation:start -->"
	end := "<!-- prabu:omo-delegation:end -->"
	block := strings.Join([]string{
		start,
		"You are the Telegram-facing personal assistant for this ZeroClaw installation.",
		"For tasks that require code, file changes, scripts, or other execution, delegate the work to OMO Native with the shell tool: run `omo -p --approve --no-session '<complete task>'` from the active workspace.",
		"Pass the user's request, relevant context, and constraints to OMO. Wait for the process to finish, inspect its exit status and output, then report the result. Never claim OMO completed work when it failed or did not run.",
		"Do not use the opencode_cli tool. Answer ordinary conversation directly. For Telegram groups, respond to direct messages or messages that mention or reply to this bot, and keep replies in the originating forum topic when one is present.",
		end,
	}, "\n")
	return upsertManagedBlock(path, start, end, block)
}

func writeServicePathDropIn(home string, executables ...string) error {
	directory := filepath.Join(home, ".config", "systemd", "user", "zeroclaw.service.d")
	path := filepath.Join(directory, "10-prabu-omo.conf")
	pathEntries := []string{"%h/.local/bin", "%h/.cargo/bin", "/usr/local/bin", "/usr/bin", "/bin"}
	seen := map[string]bool{
		filepath.Join(home, ".local", "bin"): true,
		filepath.Join(home, ".cargo", "bin"): true,
		"/usr/local/bin":                     true,
		"/usr/bin":                           true,
		"/bin":                               true,
	}
	for _, executablePath := range executables {
		executableDirectory := filepath.Dir(executablePath)
		if seen[executableDirectory] {
			continue
		}
		if strings.ContainsAny(executableDirectory, ":\r\n") {
			return fmt.Errorf("cannot add executable directory %q to the systemd PATH", executableDirectory)
		}
		seen[executableDirectory] = true
		escapedDirectory := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `%`, `%%`).Replace(executableDirectory)
		pathEntries = append(pathEntries, escapedDirectory)
	}
	content := strings.Join([]string{
		managedMarker,
		"[Service]",
		`Environment="PATH=` + strings.Join(pathEntries, ":") + `"`,
		"",
	}, "\n")
	if err := os.MkdirAll(directory, 0o700); err != nil {
		return fmt.Errorf("create ZeroClaw service override directory: %w", err)
	}
	if existing, err := os.ReadFile(path); err == nil && !strings.Contains(string(existing), managedMarker) {
		return fmt.Errorf("refusing to overwrite unmanaged ZeroClaw service override %s", path)
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read ZeroClaw service override %s: %w", path, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		return fmt.Errorf("write ZeroClaw service override %s: %w", path, err)
	}
	return nil
}

func upsertManagedBlock(path, start, end, block string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return fmt.Errorf("create ZeroClaw agent workspace: %w", err)
	}
	current, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read ZeroClaw agent instructions %s: %w", path, err)
	}
	text := string(current)
	startIndex := strings.Index(text, start)
	if startIndex >= 0 {
		endIndex := strings.Index(text[startIndex:], end)
		if endIndex < 0 {
			return fmt.Errorf("managed OMO instruction block in %s has no end marker", path)
		}
		endIndex += startIndex + len(end)
		text = text[:startIndex] + block + text[endIndex:]
	} else if text == "" {
		text = block + "\n"
	} else {
		text = strings.TrimRight(text, "\n") + "\n\n" + block + "\n"
	}
	if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
		return fmt.Errorf("write ZeroClaw agent instructions %s: %w", path, err)
	}
	return nil
}
